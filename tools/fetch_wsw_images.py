#!/usr/bin/env python3
"""Fetch the Witham-Maldon-South Woodham Ferrers photos from Wikimedia Commons.

Downloads 900px renditions into game/img/wsw/ and writes game/wsw-images.js with
author, licence and source links, so credits are generated, not hand-typed.
Every file here is CC BY-SA or public domain; attribution is shown in-game and
on game/credits.html.
"""
import html, json, os, re, sys, time, urllib.parse, urllib.request

UA = {'User-Agent': 'tpw-research/1.0 (jon@splippers.com)'}
OUT = os.path.join(os.path.dirname(__file__), '..', 'game')
IMG = os.path.join(OUT, 'img', 'wsw')

# key -> Commons file title
FILES = {
    'witham': 'File:Witham railway station 20170609.jpg',
    'viaduct': 'File:Wickham Bishops timber trestle railway viaduct - geograph.org.uk - 3813346.jpg',
    'wickham_bridge': 'File:Old railway bridge, Wickham Bishops - geograph.org.uk - 4536376.jpg',
    'trail': 'File:Blackwater Rail Trail - geograph.org.uk - 7700200.jpg',
    'maldon_east': 'File:Former Maldon East Railway Station - geograph.org.uk - 787042.jpg',
    'maldon_east_2': 'File:Maldon East Railway Station - geograph.org.uk - 519479.jpg',
    'maldon_1851': 'File:ECR(1851) p61b - Maldon Railway Station.jpg',
    'maldon_west_embankment': 'File:Branch Line - geograph.org.uk - 973697.jpg',
    'lost_line': 'File:Lost Line to Cold Norton - geograph.org.uk - 288902.jpg',
    'cold_norton_1909': 'File:Cold Norton railway station.jpg',
    'cold_norton_1984': 'File:Cold Norton station geograph-3086230-by-Ben-Brooksbank.jpg',
    'stow_maries': 'File:Old Trackbed at Stow Maries Halt Nature Reserve - geograph.org.uk - 3463285.jpg',
    'swf': 'File:South Woodham Ferrers railway station in 2008.jpg',
    'map_1889': 'File:Maldon-lines-1889.png',
    'map_1848': 'File:Maldon-lines.png',
}

def api(**p):
    p['format'] = 'json'
    r = urllib.request.Request('https://commons.wikimedia.org/w/api.php?' + urllib.parse.urlencode(p), headers=UA)
    return json.load(urllib.request.urlopen(r))

def clean(v):
    return re.sub(r'\s+', ' ', html.unescape(re.sub(r'<[^>]+>', '', v or ''))).strip()

os.makedirs(IMG, exist_ok=True)
d = api(action='query', titles='|'.join(FILES.values()), prop='imageinfo', iiprop='url|extmetadata', iiurlwidth=900)
by_title = {p['title']: p for p in d['query']['pages'].values()}
out = {}
for key, title in FILES.items():
    norm = next(t for t in by_title if t.replace('_', ' ') == title.replace('_', ' '))
    ii = by_title[norm]['imageinfo'][0]
    m = ii['extmetadata']
    lic = clean(m.get('LicenseShortName', {}).get('value'))
    assert lic.startswith(('CC BY', 'Public domain')), (title, lic)
    ext = 'png' if title.endswith('.png') else 'jpg'
    path = os.path.join(IMG, key + '.' + ext)
    if not os.path.exists(path):
        r = urllib.request.Request(ii['thumburl'], headers=UA)
        open(path, 'wb').write(urllib.request.urlopen(r).read())
        time.sleep(1)
    out[key] = {
        'file': 'img/wsw/%s.%s' % (key, ext),
        'title': clean(title.replace('File:', '').rsplit('.', 1)[0]),
        'author': clean(m.get('Artist', {}).get('value')) or 'Unknown (public domain)',
        'license': lic,
        'licenseUrl': clean(m.get('LicenseUrl', {}).get('value')),
        'source': 'https://commons.wikimedia.org/wiki/' + urllib.parse.quote(title.replace(' ', '_')),
    }
    print(key, lic, '|', out[key]['author'])
open(os.path.join(OUT, 'wsw-images.js'), 'w').write(
    '// Generated by tools/fetch_wsw_images.py. Do not edit.\nconst WSW_IMAGES=%s;\n' % json.dumps(out, indent=1))
