#!/usr/bin/env python3
"""Build game/map-data.js (coastlines + city positions) from real geography.

Usage: build_map.py ne_10m_admin_0_map_units.geojson > game/map-data.js
Source: Natural Earth (public domain). Projection: equirectangular, scaled by
cos(54.5N) so Britain isn't stretched. Output fits the game's 600x800 viewBox.
"""
import json, math, sys

LON0, LON1, LAT0, LAT1 = -10.7, 2.0, 49.8, 61.0
H = 800.0
KY = H / (LAT1 - LAT0)
KX = KY * math.cos(math.radians(54.5))
XOFF = (600 - (LON1 - LON0) * KX) / 2

